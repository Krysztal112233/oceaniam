import { promises as fs } from "node:fs";
import path from "node:path";

const pkgDir = process.cwd();
const typesDir = path.join(pkgDir, "src", "types");
const outputFile = path.join(typesDir, "index.ts");

async function collectTypeFiles(dir) {
  const dirents = await fs.readdir(dir, { withFileTypes: true });
  const filePaths = [];

  for (const dirent of dirents) {
    const filePath = path.join(dir, dirent.name);

    if (dirent.isDirectory()) {
      filePaths.push(...(await collectTypeFiles(filePath)));
      continue;
    }

    if (!dirent.isFile()) continue;
    if (!dirent.name.endsWith(".ts")) continue;
    if (dirent.name === "index.ts") continue;

    filePaths.push(filePath);
  }

  return filePaths;
}

const typeFiles = await collectTypeFiles(typesDir);
const exports = typeFiles
  .map((filePath) => path.relative(typesDir, filePath))
  .sort((a, b) => a.localeCompare(b))
  .map((relativePath) => relativePath.replace(/\.ts$/i, ""))
  .map((relativePath) => relativePath.split(path.sep).join("/"))
  .map((relativePath) => `export type * from "./${relativePath}";`);

const content = [
  "// This file is generated by `pnpm -C ../sdk/typescript gen:types-index`.",
  "// Do not edit manually.",
  "",
  ...exports,
  "",
].join("\n");

await fs.writeFile(outputFile, content, "utf8");
